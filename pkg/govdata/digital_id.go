package govdata

import (
	"context"
	"errors"
	"fmt"
	"net/url"
	"strings"
	"time"
)

// ErrDigitalIDProtocolUnavailable means a jurisdiction adapter has not been
// implemented as a verified protocol client. Callers must treat this as a hard
// failure, never as a successful or partial identity verification.
var ErrDigitalIDProtocolUnavailable = errors.New("digital identity protocol is not configured")

// AssuranceLevel is the provider-neutral assurance outcome. Provider-specific
// values must be explicitly mapped; unknown values are never upgraded.
type AssuranceLevel string

const (
	AssuranceLevelUnknown     AssuranceLevel = "unknown"
	AssuranceLevelLow         AssuranceLevel = "low"
	AssuranceLevelSubstantial AssuranceLevel = "substantial"
	AssuranceLevelHigh        AssuranceLevel = "high"
)

func (l AssuranceLevel) Valid() bool {
	switch l {
	case AssuranceLevelLow, AssuranceLevelSubstantial, AssuranceLevelHigh:
		return true
	default:
		return false
	}
}

// PKCEMethod identifies the only code challenge transformation accepted by the
// neutral contract. Plain PKCE is intentionally unsupported.
type PKCEMethod string

const PKCEMethodS256 PKCEMethod = "S256"

// DigitalIDAuthorizationRequest contains a stateful authorization request.
// State, nonce, and code challenge are generated by the relying party and
// stored server-side until the callback is consumed exactly once.
type DigitalIDAuthorizationRequest struct {
	ProviderID          string
	ClientID            string
	RedirectURI         string
	State               string
	Nonce               string
	CodeChallenge       string
	CodeChallengeMethod PKCEMethod
	ConsentID           string
	RequestedClaims     []string
	MinimumAssurance    AssuranceLevel
	ExpiresAt           time.Time
}

func (r DigitalIDAuthorizationRequest) Validate(now time.Time) error {
	for name, value := range map[string]string{"provider_id": r.ProviderID, "client_id": r.ClientID, "state": r.State, "nonce": r.Nonce, "code_challenge": r.CodeChallenge, "consent_id": r.ConsentID} {
		if strings.TrimSpace(value) == "" || len(value) > 512 {
			return fmt.Errorf("digital ID %s is required and bounded", name)
		}
	}
	redirect, err := url.ParseRequestURI(r.RedirectURI)
	if err != nil || redirect.Scheme != "https" || redirect.Host == "" || redirect.Fragment != "" {
		return fmt.Errorf("digital ID redirect URI must be an absolute HTTPS URI without a fragment")
	}
	if r.CodeChallengeMethod != PKCEMethodS256 {
		return fmt.Errorf("digital ID requires PKCE S256")
	}
	if len(r.State) < 16 || len(r.Nonce) < 16 || len(r.CodeChallenge) < 43 || len(r.CodeChallenge) > 128 {
		return fmt.Errorf("digital ID state, nonce, or PKCE challenge is too short")
	}
	if !r.MinimumAssurance.Valid() {
		return fmt.Errorf("digital ID minimum assurance is invalid")
	}
	if r.ExpiresAt.IsZero() || !r.ExpiresAt.After(now.UTC()) || r.ExpiresAt.Sub(now.UTC()) > 15*time.Minute {
		return fmt.Errorf("digital ID authorization expiry must be within 15 minutes")
	}
	if len(r.RequestedClaims) == 0 {
		return fmt.Errorf("digital ID requested claims are required")
	}
	seen := make(map[string]struct{}, len(r.RequestedClaims))
	for _, claim := range r.RequestedClaims {
		claim = strings.TrimSpace(claim)
		if claim == "" || len(claim) > 128 {
			return fmt.Errorf("digital ID requested claim is invalid")
		}
		if _, exists := seen[claim]; exists {
			return fmt.Errorf("digital ID requested claims must be unique")
		}
		seen[claim] = struct{}{}
	}
	return nil
}

// DigitalIDCallback is delivered by an authorization response. The callback
// does not contain a verification result; provider implementations must redeem
// and validate the code before returning an identity.
type DigitalIDCallback struct {
	State string
	Code  string
	Error string
}

// DigitalIDIdentity is the minimal normalized identity result. Claims must be
// verified by the provider protocol implementation, with subject pairwise or
// otherwise privacy-preserving for the relying-party sector.
type DigitalIDIdentity struct {
	ProviderID string
	Subject    string
	Assurance  AssuranceLevel
	Claims     map[string]string
	IssuedAt   time.Time
	ExpiresAt  time.Time
	Status     CredentialStatus
}

// CredentialStatus is a remotely checked credential lifecycle state.
type CredentialStatus string

const (
	CredentialStatusActive  CredentialStatus = "active"
	CredentialStatusRevoked CredentialStatus = "revoked"
	CredentialStatusExpired CredentialStatus = "expired"
	CredentialStatusUnknown CredentialStatus = "unknown"
)

// DigitalIDProvider is implemented by OpenID4VP/OpenID4VCI, SD-JWT VC, mdoc,
// or jurisdiction profile adapters. Implementations must validate issuer
// metadata, signatures, nonce/audience binding, consent and credential status
// before returning DigitalIDIdentity.
type DigitalIDProvider interface {
	ProviderID() string
	BeginAuthorization(context.Context, DigitalIDAuthorizationRequest) (string, error)
	CompleteAuthorization(context.Context, DigitalIDAuthorizationRequest, DigitalIDCallback) (DigitalIDIdentity, error)
	CredentialStatus(context.Context, DigitalIDIdentity) (CredentialStatus, error)
}

// DigitalIDCapableAdapter lets callers discover a provider-neutral Digital ID
// authorization bridge without treating a document verification adapter as a
// complete identity-provider implementation.
type DigitalIDCapableAdapter interface {
	DigitalIDProvider() DigitalIDProvider
}

// ValidateIdentity fails closed unless the response satisfies the originally
// authorized provider, assurance, expiry, consent-bound request, and live
// credential status requirements.
func ValidateIdentity(request DigitalIDAuthorizationRequest, identity DigitalIDIdentity, now time.Time) error {
	if identity.ProviderID != request.ProviderID || strings.TrimSpace(identity.Subject) == "" {
		return fmt.Errorf("digital ID identity provider or subject binding mismatch")
	}
	if !identity.Assurance.Valid() || assuranceRank(identity.Assurance) < assuranceRank(request.MinimumAssurance) {
		return fmt.Errorf("digital ID assurance requirement not met")
	}
	if identity.IssuedAt.IsZero() || identity.ExpiresAt.IsZero() || !identity.ExpiresAt.After(now.UTC()) || identity.IssuedAt.After(now.UTC()) {
		return fmt.Errorf("digital ID identity timing is invalid")
	}
	if identity.Status != CredentialStatusActive {
		return fmt.Errorf("digital ID credential is not active")
	}
	for _, claim := range request.RequestedClaims {
		if strings.TrimSpace(identity.Claims[claim]) == "" {
			return fmt.Errorf("digital ID response omitted requested claim %q", claim)
		}
	}
	return nil
}

func assuranceRank(level AssuranceLevel) int {
	switch level {
	case AssuranceLevelHigh:
		return 3
	case AssuranceLevelSubstantial:
		return 2
	case AssuranceLevelLow:
		return 1
	default:
		return 0
	}
}

// UnavailableDigitalIDProvider is a deliberate fail-closed bridge for legacy
// DVS/eIDAS configuration. It prevents an operator from mistaking an HTTP
// adapter for a complete browser/wallet authorization protocol.
type UnavailableDigitalIDProvider struct{ ID string }

func (p UnavailableDigitalIDProvider) ProviderID() string { return p.ID }
func (p UnavailableDigitalIDProvider) BeginAuthorization(context.Context, DigitalIDAuthorizationRequest) (string, error) {
	return "", ErrDigitalIDProtocolUnavailable
}
func (p UnavailableDigitalIDProvider) CompleteAuthorization(context.Context, DigitalIDAuthorizationRequest, DigitalIDCallback) (DigitalIDIdentity, error) {
	return DigitalIDIdentity{}, ErrDigitalIDProtocolUnavailable
}
func (p UnavailableDigitalIDProvider) CredentialStatus(context.Context, DigitalIDIdentity) (CredentialStatus, error) {
	return CredentialStatusUnknown, ErrDigitalIDProtocolUnavailable
}
