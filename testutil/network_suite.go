// DefaultTestTimeout is the wall-clock budget for a single test method in a
// NetworkTestSuite. It is a hang guard, not a per-transaction budget: a test
// that broadcasts N transactions serially must fit N round trips inside it.
// The old fixed 30s value was shorter than a single multi-tx CLI test needs on
// a loaded Windows CI runner, which made ValidateTx abort mid-suite and report
// the still-pending tx as "not found".
const DefaultTestTimeout = 5 * time.Minute

type NetworkTestSuite struct {
	*suite.Suite
	cfg           network.Config
	network       *network.Network
	testIdx       int
	kr            keyring.Keyring
	testCtx       context.Context
	cancelTestCtx context.CancelFunc
	container     interface{}
	testTimeout   time.Duration
}

func NewNetworkTestSuite(cfg *network.Config, container interface{}) *NetworkTestSuite {
	nts := &NetworkTestSuite{
		Suite:       &suite.Suite{},
		testIdx:     -1,
		container:   container,
		testTimeout: DefaultTestTimeout,
	}
	if cfg == nil {
		nts.cfg = network.DefaultConfig(NewTestNetworkFixture)
		nts.cfg.NumValidators = 1
	} else {
		nts.cfg = *cfg
	}

	return nts
}

// containerT asks the container for its *testing.T. A suite literal handed to
// NewNetworkTestSuite is normally a fresh zero-valued value: the embedded
// *NetworkTestSuite field is only assigned once the returned suite is stored
// back into it, so the throwaway captured at construction time promotes T()
// through a nil embed. Calling it then panics with a nil pointer dereference
// instead of answering, which aborts SetupSuite before the network is built:
//
//	panic.go:336: test panicked: runtime error: invalid memory address or nil pointer dereference
//	(*HPCMarketplaceE2ETestSuite).T(...) <autogenerated>:1
//	(*NetworkTestSuite).syncTestingContext(...) testutil/network_suite.go:76
//
// Such a container simply cannot report a T; that is not an error, so the probe
// recovers and reports nil. When the container *can* answer, behaviour is
// unchanged.
func containerT(container interface{}) (t *testing.T) {
	outer, ok := container.(interface{ T() *testing.T })
	if !ok {
		return nil
	}
	defer func() {
		if r := recover(); r != nil {
			t = nil
		}
	}()
	return outer.T()
}

func (nts *NetworkTestSuite) syncTestingContext() {
	if nts.container == nil {
		return
	}

	if t := containerT(nts.container); t != nil {
		nts.SetT(t)
	}
}

func (nts *NetworkTestSuite) countTests() int {
	vof := reflect.TypeOf(nts.container)

	cnt := 0
	for i := 0; i != vof.NumMethod(); i++ {
		method := vof.Method(i)
		methodName := method.Name
		if strings.HasPrefix(methodName, "Test") {
			cnt++
		}
	}

	return cnt
}

func (nts *NetworkTestSuite) TearDownSuite() {
	nts.network.Cleanup()
}

