package testutil

import (
	"testing"

	"github.com/stretchr/testify/suite"
)

// nilEmbedSuite is the construction every tests/e2e suite uses: the container
// literal handed to NewNetworkTestSuite is a throwaway, so the value captured as
// nts.container has a nil embedded *NetworkTestSuite and cannot answer T().
// Its SetupSuite enters through the embedded suite exactly as
// HPCMarketplaceE2ETestSuite.SetupSuite does, which is where CI panicked:
//
//	panic.go:336: test panicked: runtime error: invalid memory address or nil pointer dereference
//	(*HPCMarketplaceE2ETestSuite).T(...) <autogenerated>:1 +0x3
//	(*NetworkTestSuite).syncTestingContext(...) testutil/network_suite.go:76 +0x8f
//	(*NetworkTestSuite).SetupSuite(...) testutil/network_suite.go:102
//	(*HPCMarketplaceE2ETestSuite).SetupSuite(...) tests/e2e/hpc_marketplace_e2e_test.go:57
type nilEmbedSuite struct {
	*NetworkTestSuite

	syncReached bool
}

func (s *nilEmbedSuite) SetupSuite() {
	// Stop just short of network.New so the regression test stays hermetic
	// while still driving syncTestingContext down the production path.
	s.syncTestingContext()
	s.syncReached = true
}

// TearDownSuite overrides the embedded no-op-unsafe teardown: the production
// NetworkTestSuite.TearDownSuite dereferences nts.network, which this hermetic
// probe never builds.
func (s *nilEmbedSuite) TearDownSuite() {}

func (s *nilEmbedSuite) TestProbeReachesBody() {
	s.Require().True(s.syncReached, "SetupSuite did not complete")
}

// TestSyncTestingContextToleratesNilEmbeddedSuite pins the CI panic above.
// syncTestingContext must treat "this container cannot report a T" as a
// no-op, not as a fatal nil pointer dereference that aborts SetupSuite before
// the network is ever built.
func TestSyncTestingContextToleratesNilEmbeddedSuite(t *testing.T) {
	nts := NewNetworkTestSuite(nil, &nilEmbedSuite{})

	defer func() {
		if r := recover(); r != nil {
			t.Fatalf("syncTestingContext panicked on a nil embedded suite: %v", r)
		}
	}()

	nts.syncTestingContext()
}

// TestSyncTestingContextStillEstablishesTUnderSuiteRun drives the real suite.Run
// path and asserts the fix does not merely swallow the panic: after SetupSuite
// the suite must still have a usable *testing.T, which testify establishes on
// the value it drives. Without this half, a fix that silently left the suite
// T-less would pass the test above.
func TestSyncTestingContextStillEstablishesTUnderSuiteRun(t *testing.T) {
	outer := &nilEmbedSuite{}
	outer.NetworkTestSuite = NewNetworkTestSuite(nil, &nilEmbedSuite{})

	suite.Run(t, outer)

	if !outer.syncReached {
		t.Fatal("syncTestingContext did not run to completion")
	}
	if outer.T() == nil {
		t.Fatal("suite has no *testing.T after SetupSuite -- T was never established")
	}
}
